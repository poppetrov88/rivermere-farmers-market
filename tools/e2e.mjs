import puppeteer from 'puppeteer-core';
const B = 'http://rivermere-farmers-market.local';
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
// Pre-set a stored cookie choice so the first-visit banner does not cover the page under test.
await browser.setCookie({ name: 'rm_consent', value: encodeURIComponent(JSON.stringify({ v: 1, n: 1, a: 0, m: 0, t: new Date().toISOString() })), domain: 'rivermere-farmers-market.local', path: '/' });
const res = [];
const ok = (n, c, extra = '') => res.push(`${c ? 'PASS' : 'FAIL'} ${n} ${extra}`);
const errs = [];
// Desktop: search
let page = await browser.newPage();
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
page.on('pageerror', (e) => errs.push(e.message));
await page.setViewport({ width: 1280, height: 800 });
await page.goto(B, { waitUntil: 'networkidle0' });
await page.focus('[data-search-open]');
await page.keyboard.press('Enter');
await new Promise((r) => setTimeout(r, 500));
ok('search opens', await page.evaluate(() => document.getElementById('search-overlay').open));
ok('input focused', await page.evaluate(() => document.activeElement.id === 'search-overlay-input'));
ok('scroll locked', await page.evaluate(() => getComputedStyle(document.body).overflow === 'hidden'));
await page.keyboard.press('Escape');
await new Promise((r) => setTimeout(r, 600));
ok('esc closes', await page.evaluate(() => !document.getElementById('search-overlay').open));
ok('focus restored', await page.evaluate(() => document.activeElement.hasAttribute('data-search-open')));
ok('scroll unlocked', await page.evaluate(() => getComputedStyle(document.body).overflow !== 'hidden'));
await page.click('[data-search-open]');
await new Promise((r) => setTimeout(r, 400));
await page.type('#search-overlay-input', 'honey');
await Promise.all([page.waitForNavigation(), page.keyboard.press('Enter')]);
ok('search results page', page.url().includes('?s=honey'), await page.$eval('h1', (e) => e.textContent));
ok('search finds vendor', (await page.$$eval('.card__title', (e) => e.map((x) => x.textContent))).some((t) => /Honey/.test(t)));
// Newsletter
await page.goto(B, { waitUntil: 'networkidle0' });
const submit = async (email, consent) => {
  await page.$eval('#newsletter-email', (e) => (e.value = ''));
  await page.type('#newsletter-email', email);
  const c = await page.$eval('#newsletter-consent', (e) => e.checked);
  if (c !== consent) await page.click('#newsletter-consent');
  await new Promise((r) => setTimeout(r, 2200));
  await page.click('[data-newsletter-submit]');
  await new Promise((r) => setTimeout(r, 1500));
  return page.$eval('#newsletter-status', (e) => `${e.dataset.state}|${e.textContent}`);
};
let s = await submit('not-an-email', true);
ok('invalid email rejected', s.startsWith('error'), s);
s = await submit('Test.User+demo@Example.com', false);
ok('consent required (inline error shown)', await page.$eval('#newsletter-consent-error', (e) => !e.hidden && e.textContent.length > 10));
s = await submit('Test.User+demo@Example.com', true);
ok('subscribe success', s.startsWith('success'), s);
s = await submit('test.user+demo@example.com', true);
ok('duplicate handled gracefully', s.startsWith('success'), s);
// Mobile nav
const m = await browser.newPage();
await m.setViewport({ width: 390, height: 800 });
await m.goto(B, { waitUntil: 'networkidle0' });
ok('nav hidden on mobile', await m.$eval('#primary-nav', (e) => getComputedStyle(e).display === 'none'));
await m.click('[data-nav-toggle]');
ok('nav opens', await m.$eval('#primary-nav', (e) => getComputedStyle(e).display !== 'none') && (await m.$eval('[data-nav-toggle]', (e) => e.getAttribute('aria-expanded'))) === 'true');
await m.keyboard.press('Escape');
ok('esc closes nav + focus on toggle', (await m.$eval('[data-nav-toggle]', (e) => e.getAttribute('aria-expanded'))) === 'false' && (await m.evaluate(() => document.activeElement.hasAttribute('data-nav-toggle'))));
console.log(res.join('\n'));
console.log('console errors:', errs.length ? errs.join(' | ') : 'none');
await browser.close();
